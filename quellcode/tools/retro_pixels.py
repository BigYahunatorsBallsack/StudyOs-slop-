def mirror_top(art, n):
    """Obere n Zeilen gespiegelt, der Rest bleibt: zweites Bild für flackernde Flammen."""
    rows = art.strip('\n').split('\n')
    return '\n' + '\n'.join([r[::-1] for r in rows[:n]] + rows[n:]) + '\n'


